const ordered = Object.entries(copy).sort((a,b)=>b[0].length-a[0].length);
export function translateText(source:string):string {
  if(!/[\u3400-\u9fff]/.test(source))return source;
  const exact=copy[source.trim()];
  if(exact!==undefined)return source.replace(source.trim(),exact);
  let translated=source;
  for(const [zh,en] of ordered) {
    if(zh.length<2 || !translated.includes(zh))continue;
    translated=translated.split(zh).join(en);
  }
  return translated;
}

const textState=new WeakMap<Text,{source:string;last:string}>();
const attrState=new WeakMap<Element,Map<string,{source:string;last:string}>>();
export function localizeDocument(locale:Locale){
  const root=document.body;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  let node:Node|null;
  while((node=walker.nextNode())){
    const text=node as Text;
    if(!text.nodeValue?.trim()||text.parentElement?.closest('script,style,[data-no-translate]'))continue;
    let state=textState.get(text);
    if(!state||state.last!==text.nodeValue){state={source:text.nodeValue,last:text.nodeValue};textState.set(text,state)}
    const next=locale==='en'?translateText(state.source):state.source;
    if(text.nodeValue!==next)text.nodeValue=next;
    state.last=next;
  }
  root.querySelectorAll?.<Element>('[placeholder],[aria-label],[title],[alt]').forEach(el=>{
    if(el.closest('[data-no-translate]'))return;
    let states=attrState.get(el);if(!states){states=new Map();attrState.set(el,states)}
    for(const key of ['placeholder','aria-label','title','alt']){
      const current=el.getAttribute(key);if(!current)continue;
      let state=states.get(key);if(!state||state.last!==current){state={source:current,last:current};states.set(key,state)}
      const next=locale==='en'?translateText(state.source):state.source;
      if(current!==next)el.setAttribute(key,next);
      state.last=next;
    }
  });
}
